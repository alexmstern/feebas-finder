// Return the Feebas tiles for a given seed.
function feebasTilesForSeed(rand) {
  const bytes = [
    (rand >>> 24) & 0xff,
    (rand >>> 16) & 0xff,
    (rand >>> 8) & 0xff,
    rand & 0xff,
  ];
  const groupSize = Math.floor(FEEBAS_TILES.length / 4); // 132
  const tiles = [];
  for (let i = 0; i < 4; i++) {
    const index = groupSize * i + (bytes[i] % groupSize);
    tiles.push(FEEBAS_TILES[index]);
  }
  return tiles;
}

// Derive potential seeds based on yesterday's and today's lottery numbers, and return the Feebas tiles for each seed.
function findFeebasTiles(prevLotto, currLotto) {
  return recoverTodaysSeeds(prevLotto, currLotto).map(seed => ({
    seed,
    tiles: feebasTilesForSeed(seed),
  }));
}