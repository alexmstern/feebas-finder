const RAND_MULTIPLIER = 1812433253, RAND_INCREMENT = 1;      // advances `rand` by one day
const LOTTO_MULTIPLIER = 1103515245, LOTTO_INCREMENT = 12345; // transforms `rand` into the shown number

function mul32(a, b) {
    return Math.imul(a, b) >>> 0;
}

// Convert a number to an unsigned 32-bit integer.
function u32(x) {
    return x >>> 0;
}

// Advance the LCRNG by one step, returning the new seed.
function advanceLCRNG(seed, multiplier, increment) {
    return u32(mul32(seed, multiplier) + increment);
}

// Advance the LCRNG by one day, returning the new seed.
function advanceOneDay(rand) {
    return advanceLCRNG(rand, RAND_MULTIPLIER, RAND_INCREMENT);
}

// Calculate the lottery number from a given `rand` value.
function lottoNumber(rand) {
    return advanceLCRNG(rand, LOTTO_MULTIPLIER, LOTTO_INCREMENT) >>> 16;
}

// Modular inverse of `a` mod 2^16, via extended Euclidean algorithm.
// (LCRNG_MULTIPLIER is odd, so this always exists.)
function modInverse16(a) {
  a = a & 0xffff;
  let [oldR, r] = [a, 0x10000];
  let [oldS, s] = [1, 0];
  while (r !== 0) {
    const q = Math.floor(oldR / r);
    [oldR, r] = [r, oldR - q * r];
    [oldS, s] = [s, oldS - q * s];
  }
  return ((oldS % 0x10000) + 0x10000) % 0x10000;
}
const LCRNG_MULT_INV16 = modInverse16(LOTTO_MULTIPLIER);

// Calculate all candidate values of TODAY's `rand` consistent with both yesterday's and today's Jubilife Lottery numbers (each 0-65535).
function recoverTodaysSeeds(prevLotto, currLotto) {
  const results = [];
  for (let L = 0; L < 0x10000; L++) {
    const base = u32(mul32(L, LOTTO_MULTIPLIER) + LOTTO_INCREMENT);
    const baseHi = base >>> 16;
    const H = mul32((prevLotto - baseHi) & 0xffff, LCRNG_MULT_INV16) & 0xffff;
    const randYesterday = u32(H * 0x10000 + L);

    const randToday = advanceOneDay(randYesterday);
    if (lottoNumber(randToday) === currLotto) {
      results.push(randToday);
    }
  }
  return results;
}

